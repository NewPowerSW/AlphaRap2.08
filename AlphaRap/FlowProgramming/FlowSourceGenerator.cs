using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Security.Cryptography;
using System.Text;
using System.Xml.Serialization;
using AlphaRap.Configuration;
using NPSDK;

namespace AlphaRap.FlowProgramming
{
    /// <summary>将主保存的同一流程快照生成为关联源码；生成文件不承担流程调度。</summary>
    public static partial class FlowSourceGenerator
    {
        private const string Owner = "AlphaRap.FlowSourceGenerator";
        private const string Header = "// <auto-generated by AlphaRap.FlowSourceGenerator>";
        private static string loadedPath;
        private static Options draft;
        private static Options saved;
        private static Options prepared;
        private static Exception loadError;

        public sealed class Options
        {
            public int Version = 1;
            public string ProjectFile;
            public string ExportDirectory;

            /// <summary>复制路径草稿，不将自动探测结果写死到分发配置。</summary>
            public Options Copy() { return (Options)MemberwiseClone(); }
        }

        public sealed class Manifest
        {
            public int Version = 1;
            public string Generator = Owner;
            public List<OwnedFile> Files = new List<OwnedFile>();
        }

        public sealed class OwnedFile
        {
            public string ModuleId;
            public string FileName;
            public string Sha256;
        }

        /// <summary>机器设置中的源码生成选项，配方切换不改变该配置。</summary>
        public static string SettingsPath { get { return Path.Combine(SysPara.SettingDataDirectory, "FlowSourceGeneration.xml"); } }

        /// <summary>明确指定源码工程；空串强制导出，未配置时仅对本工程开发 EXE 自动探测。</summary>
        public static string SourceProjectPath
        {
            get { EnsureLoaded(); return ResolveProject(draft); }
            set { EnsureLoaded(); draft.ProjectFile = value == null ? null : string.IsNullOrWhiteSpace(value) ? "" : Path.GetFullPath(value); }
        }

        /// <summary>开发工程使用其 GeneratedFlows；发布程序可明确指定导出目录。</summary>
        public static string OutputDirectory
        {
            get { EnsureLoaded(); return ResolveOutput(draft); }
            set
            {
                EnsureLoaded();
                if (string.IsNullOrWhiteSpace(value)) throw new ArgumentException(Text("outputRequired", "请选择源码输出目录。", "Choose a source output directory.", "Seleccione una carpeta de salida de código."));
                string path = Path.GetFullPath(value);
                if (!string.IsNullOrEmpty(ResolveProject(draft)) && !SamePath(path, ResolveOutput(draft)))
                    throw new InvalidOperationException(Text("managedOutput", "开发工程的源码只生成到该工程的 GeneratedFlows 目录。", "Development sources must be generated in the project's GeneratedFlows directory.", "El código de desarrollo debe generarse en GeneratedFlows del proyecto."));
                draft.ExportDirectory = path;
            }
        }

        /// <summary>显示当前关联或导出路径，并明确生成源码仍需编译。</summary>
        public static string ModeDescription
        {
            get
            {
                EnsureLoaded();
                if (loadError != null) return Text("settingsError", "源码生成设置无法读取，主保存前请修复：{0}", "Source generation settings cannot be read; repair before Main Save: {0}", "No se puede leer la configuración de generación; repárela antes de guardar: {0}", SettingsPath);
                return string.IsNullOrEmpty(ResolveProject(draft))
                    ? Text("exportMode", "关联源码包：{0}（不修改已运行程序，需编译后使用）", "Linked source package: {0} (the running program is unchanged; compile before use)", "Paquete de código vinculado: {0} (el programa en ejecución no cambia; compile antes de usar)", ResolveOutput(draft))
                    : Text("projectMode", "工程关联源码：{0}（主保存后生成，纳入工程编译后生效）", "Project-linked sources: {0} (generated by Main Save; include them in the project and rebuild)", "Código vinculado al proyecto: {0} (se genera al guardar; inclúyalo en el proyecto y recompile)", ResolveOutput(draft));
            }
        }

        /// <summary>判断源码路径配置是否存在尚未主保存的修改。</summary>
        public static bool HasChanges
        {
            get { EnsureLoaded(); return draft.ProjectFile != saved.ProjectFile || draft.ExportDirectory != saved.ExportDirectory; }
        }

        /// <summary>生成源码、配置及所有权清单的暂存任务，不写正式文件或接受草稿。</summary>
        internal static List<ProjectConfiguration.PendingFile> Prepare(FlowProject snapshot)
        {
            if (snapshot == null) throw new ArgumentNullException("snapshot");
            EnsureLoaded();
            if (loadError != null) throw new InvalidOperationException(Text("settingsError", "源码生成设置无法读取，主保存前请修复：{0}", "Source generation settings cannot be read; repair before Main Save: {0}", "No se puede leer la configuración de generación; repárela antes de guardar: {0}", SettingsPath), loadError);
            Options options = draft.Copy();
            string project = ResolveProject(options);
            string output = ResolveOutput(options);
            if (!string.IsNullOrEmpty(project) && !File.Exists(project)) throw new FileNotFoundException(Text("projectMissing", "源码工程不存在：{0}", "The source project does not exist: {0}", "El proyecto de código no existe: {0}", project), project);
            string manifestPath = Path.Combine(output, "FlowSources.manifest.xml");
            Manifest previous = ReadManifest(manifestPath);
            Manifest next = new Manifest();
            List<ProjectConfiguration.PendingFile> files = new List<ProjectConfiguration.PendingFile>();
            Dictionary<string, FlowProgram> programs = snapshot.Modules.ToDictionary(module => module.ModuleId, StringComparer.Ordinal);
            foreach (OwnedFile old in previous.Files)
                if (!programs.ContainsKey(old.ModuleId)) programs.Add(old.ModuleId, new FlowProgram { ModuleId = old.ModuleId, Removed = true, Mode = "Disabled" });
            foreach (FlowProgram module in programs.Values.OrderBy(module => module.ModuleId, StringComparer.Ordinal))
            {
                OwnedFile old = previous.Files.SingleOrDefault(file => file.ModuleId == module.ModuleId);
                string fileName = old == null ? FileName(module.ModuleId) : old.FileName;
                string target = OwnedPath(output, fileName);
                byte[] original = File.Exists(target) ? File.ReadAllBytes(target) : null;
                ValidateOwnership(target, original, old);
                string source = Render(module, project);
                byte[] bytes = new UTF8Encoding(false).GetBytes(source);
                files.Add(Pending(target, bytes, original));
                next.Files.Add(new OwnedFile { ModuleId = module.ModuleId, FileName = fileName, Sha256 = Hash(bytes) });
            }
            files.Add(Pending(manifestPath, Serialize(next), File.Exists(manifestPath) ? File.ReadAllBytes(manifestPath) : null));
            files.Add(Pending(SettingsPath, Serialize(options), File.Exists(SettingsPath) ? File.ReadAllBytes(SettingsPath) : null));
            prepared = options;
            return files;
        }

        /// <summary>全部主保存文件提交成功后接受路径设置，不读写文件。</summary>
        internal static void AcceptSaved()
        {
            if (prepared == null) return;
            saved = prepared.Copy();
            draft = prepared.Copy();
            prepared = null;
        }

        /// <summary>先读取可恢复设置，再返回只提交内存的放弃操作；已保存源码不重新生成。</summary>
        internal static Action PrepareDiscard()
        {
            EnsureLoaded();
            Options restored = new Options();
            try
            {
                if (File.Exists(SettingsPath))
                    using (FileStream stream = File.OpenRead(SettingsPath)) restored = (Options)new XmlSerializer(typeof(Options)).Deserialize(stream);
                if (restored.Version != 1) throw new InvalidDataException("Unsupported source generation settings version.");
            }
            catch (Exception error) { throw new InvalidOperationException(Text("settingsError", "源码生成设置无法读取，主保存前请修复：{0}", "Source generation settings cannot be read; repair before Main Save: {0}", "No se puede leer la configuración de generación; repárela antes de guardar: {0}", SettingsPath), error); }
            return () => { saved = restored.Copy(); draft = restored.Copy(); prepared = null; loadError = null; };
        }

        /// <summary>按当前机器设置目录延迟加载配置，失败时保留错误并阻止覆盖。</summary>
        private static void EnsureLoaded()
        {
            string path = Path.GetFullPath(SettingsPath);
            if (SamePath(loadedPath, path)) return;
            loadedPath = path;
            saved = new Options();
            loadError = null;
            prepared = null;
            try
            {
                if (File.Exists(path))
                    using (FileStream stream = File.OpenRead(path)) saved = (Options)new XmlSerializer(typeof(Options)).Deserialize(stream);
                if (saved.Version != 1) throw new InvalidDataException("Unsupported source generation settings version.");
            }
            catch (Exception error) { loadError = error; saved = new Options(); }
            draft = saved.Copy();
        }

        /// <summary>仅使用明确配置的工程，或确认来自该工程 bin 的 AlphaRap 开发程序。</summary>
        private static string ResolveProject(Options options)
        {
            if (options.ProjectFile != null) return options.ProjectFile;
            Assembly entry = Assembly.GetEntryAssembly();
            if (entry == null || entry.GetName().Name != "AlphaRap") return "";
            string executable = Path.GetFullPath(entry.Location);
            DirectoryInfo directory = new DirectoryInfo(Path.GetDirectoryName(executable));
            while (directory != null)
            {
                string direct = Path.Combine(directory.FullName, "AlphaRap.csproj");
                string nested = Path.Combine(directory.FullName, "AlphaRap", "AlphaRap.csproj");
                foreach (string candidate in new[] { direct, nested })
                    if (File.Exists(candidate) && executable.StartsWith(Path.Combine(Path.GetDirectoryName(candidate), "bin") + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase)) return candidate;
                directory = directory.Parent;
            }
            return "";
        }

        /// <summary>开发源码限于工程 GeneratedFlows，发布程序默认向机器设置目录导出。</summary>
        private static string ResolveOutput(Options options)
        {
            string project = ResolveProject(options);
            if (!string.IsNullOrEmpty(project)) return Path.GetFullPath(Path.Combine(Path.GetDirectoryName(project), "GeneratedFlows"));
            return Path.GetFullPath(string.IsNullOrWhiteSpace(options.ExportDirectory) ? Path.Combine(SysPara.SettingDataDirectory, "GeneratedFlows") : options.ExportDirectory);
        }

        /// <summary>读取并核对所有权清单，异常清单不被新清单替换。</summary>
        private static Manifest ReadManifest(string path)
        {
            if (!File.Exists(path)) return new Manifest();
            Manifest manifest;
            try
            {
                using (FileStream stream = File.OpenRead(path)) manifest = (Manifest)new XmlSerializer(typeof(Manifest)).Deserialize(stream);
            }
            catch (Exception error) { throw new InvalidDataException(Text("manifestInvalid", "源码所有权清单损坏：{0}", "The source ownership manifest is invalid: {0}", "El manifiesto de propiedad del código no es válido: {0}", path), error); }
            if (manifest.Version != 1 || manifest.Generator != Owner || manifest.Files == null || manifest.Files.Any(file => string.IsNullOrEmpty(file.ModuleId) || string.IsNullOrEmpty(file.FileName) || string.IsNullOrEmpty(file.Sha256)) || manifest.Files.GroupBy(file => file.ModuleId).Any(group => group.Count() > 1) || manifest.Files.GroupBy(file => file.FileName, StringComparer.OrdinalIgnoreCase).Any(group => group.Count() > 1))
                throw new InvalidDataException(Text("manifestInvalid", "源码所有权清单损坏：{0}", "The source ownership manifest is invalid: {0}", "El manifiesto de propiedad del código no es válido: {0}", path));
            foreach (OwnedFile file in manifest.Files) OwnedPath(Path.GetDirectoryName(path), file.FileName);
            return manifest;
        }

        /// <summary>正式源码只能覆盖本生成器登记且内容未被手工修改的文件。</summary>
        private static void ValidateOwnership(string path, byte[] bytes, OwnedFile owner)
        {
            if (bytes == null) return;
            if (owner != null && string.Equals(owner.Sha256, Hash(bytes), StringComparison.OrdinalIgnoreCase) && Encoding.UTF8.GetString(bytes).StartsWith(Header, StringComparison.Ordinal)) return;
            throw new IOException(Text("sourceConflict", "源码文件不属于生成器或已被手工修改，请保留后处理冲突：{0}", "This source file is unowned or manually modified; preserve it and resolve the conflict: {0}", "Este archivo no pertenece al generador o fue modificado; consérvelo y resuelva el conflicto: {0}", path));
        }

        /// <summary>仅允许生成目录内的单个 C# 文件名，阻止清单指向手写或上级文件。</summary>
        private static string OwnedPath(string directory, string name)
        {
            if (string.IsNullOrEmpty(name) || name != Path.GetFileName(name) || name.IndexOfAny(new[] { '/', '\\', ':' }) >= 0 || !name.EndsWith(".Flow.g.cs", StringComparison.OrdinalIgnoreCase))
                throw new InvalidDataException(Text("manifestPath", "源码清单包含不允许的路径。", "The source manifest contains a disallowed path.", "El manifiesto de código contiene una ruta no permitida."));
            return Path.GetFullPath(Path.Combine(directory, name));
        }

        /// <summary>以模块身份生成稳定文件名，名称修改不按标题搜索或删除代码。</summary>
        private static string FileName(string moduleId)
        {
            string[] parts = (moduleId ?? "").Split(new[] { '/' }, 2);
            string label = parts[0] == typeof(Flow_BaseForm).FullName && parts.Length > 1 ? parts[1] : parts[0].Split('.').Last();
            string safe = new string(label.Select(character => char.IsLetterOrDigit(character) || character == '_' ? character : '_').ToArray());
            if (safe.Length == 0) safe = "Flow";
            if (safe.Length > 64) safe = safe.Substring(0, 64);
            if (new[] { "CON", "PRN", "AUX", "NUL", "COM1", "COM2", "COM3", "COM4", "COM5", "COM6", "COM7", "COM8", "COM9", "LPT1", "LPT2", "LPT3", "LPT4", "LPT5", "LPT6", "LPT7", "LPT8", "LPT9" }.Contains(safe, StringComparer.OrdinalIgnoreCase)) safe = "Flow_" + safe;
            return safe + "." + Hash(Encoding.UTF8.GetBytes(moduleId ?? "")).Substring(0, 16) + ".Flow.g.cs";
        }

        /// <summary>捕获字节与原文件版本，准备和提交阶段均防止覆盖外部改动。</summary>
        private static ProjectConfiguration.PendingFile Pending(string path, byte[] bytes, byte[] original)
        {
            return new ProjectConfiguration.PendingFile { Path = path, Write = temporary => File.WriteAllBytes(temporary, bytes), ExpectedOriginal = original, CheckExpectedOriginal = true };
        }

        /// <summary>序列化小型设置及所有权清单，不将流程正文藏入 XML 字符串。</summary>
        private static byte[] Serialize<T>(T value)
        {
            using (MemoryStream stream = new MemoryStream())
            {
                new XmlSerializer(typeof(T)).Serialize(stream, value);
                return stream.ToArray();
            }
        }

        /// <summary>计算确定性的文件摘要用于所有权与外部修改检测。</summary>
        private static string Hash(byte[] bytes)
        {
            using (SHA256 algorithm = SHA256.Create()) return BitConverter.ToString(algorithm.ComputeHash(bytes)).Replace("-", "").ToLowerInvariant();
        }

        /// <summary>比较 Windows 正规化路径；空值只与空值相同。</summary>
        private static bool SamePath(string left, string right)
        {
            if (left == null || right == null) return left == right;
            return string.Equals(Path.GetFullPath(left).TrimEnd(Path.DirectorySeparatorChar), Path.GetFullPath(right).TrimEnd(Path.DirectorySeparatorChar), StringComparison.OrdinalIgnoreCase);
        }

        /// <summary>通过现有语言表格式化源码生成提示，业务路径不作为语言键。</summary>
        private static string Text(string key, string chinese, string english, string spanish, params object[] values)
        {
            string format = MiddleLayer.LangMsg("FlowSourceGeneration", key, chinese, english, spanish);
            return values.Length == 0 ? format : string.Format(format, values);
        }
    }
}
